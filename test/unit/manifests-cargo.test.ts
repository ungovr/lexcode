import { describe, expect, it } from 'vitest';
import { isCargoManifest, readCargo } from '../../src/manifests/cargo.js';
import { lineOf, tree } from './helpers.js';

function lock(pkgs: { name: string; version: string; source?: string }[]): string {
  const out = ['# This file is automatically @generated by Cargo.', '# It is not intended for manual editing.', 'version = 4', ''];
  for (const p of pkgs) {
    out.push('[[package]]', `name = "${p.name}"`, `version = "${p.version}"`);
    if (p.source) out.push(`source = "${p.source}"`);
    out.push('');
  }
  return out.join('\n');
}

const CRATES = 'registry+https://github.com/rust-lang/crates.io-index';

const UNRESOLVED = (n: number): string =>
  `${n} Cargo ${n === 1 ? 'dependency has' : 'dependencies have'} no resolved version (no Cargo.lock, or a requirement lexcode could not match to one locked version); recorded without a version`;

describe('isCargoManifest', () => {
  it('is true for Cargo.toml anywhere, and nothing else', () => {
    expect(isCargoManifest('Cargo.toml')).toBe(true);
    expect(isCargoManifest('crates/app/Cargo.toml')).toBe(true);
    expect(isCargoManifest('Cargo.lock')).toBe(false);
    expect(isCargoManifest('cargo.toml')).toBe(false);
    expect(isCargoManifest('pyproject.toml')).toBe(false);
  });
});

describe('readCargo', () => {
  it('reads a dependency with its locked version', () => {
    const manifest = ['[package]', 'name = "app"', 'version = "0.1.0"', 'edition = "2021"', '', '[dependencies]', 'reqwest = "0.12"', ''].join('\n');
    const root = tree({
      'Cargo.toml': manifest,
      'Cargo.lock': lock([
        { name: 'app', version: '0.1.0' },
        { name: 'reqwest', version: '0.12.9', source: CRATES },
      ]),
    });
    const r = readCargo(root, ['Cargo.toml', 'Cargo.lock']);
    expect(r.deps).toEqual([{ ecosystem: 'cargo', name: 'reqwest', version: '0.12.9', manifest: 'Cargo.toml:7' }]);
    expect(r.devSkipped).toBe(0);
    expect(r.notices).toEqual([]);
  });

  it('table form and target dependencies', () => {
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies.tokio]',
      'version = "1"',
      'features = ["full"]',
      '',
      "[target.'cfg(unix)'.dependencies]",
      'nix = "0.29"',
      '',
    ].join('\n');
    const root = tree({
      'Cargo.toml': manifest,
      'Cargo.lock': lock([
        { name: 'nix', version: '0.29.0', source: CRATES },
        { name: 'tokio', version: '1.41.1', source: CRATES },
      ]),
    });
    const r = readCargo(root, ['Cargo.toml']);
    expect(r.deps).toEqual([
      { ecosystem: 'cargo', name: 'tokio', version: '1.41.1', manifest: `Cargo.toml:${lineOf(manifest, '[dependencies.tokio]')}` },
      { ecosystem: 'cargo', name: 'nix', version: '0.29.0', manifest: `Cargo.toml:${lineOf(manifest, 'nix =')}` },
    ]);
    expect(r.devSkipped).toBe(0);
    expect(r.notices).toEqual([]);
  });

  it('dev and build dependencies are development', () => {
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dev-dependencies]',
      'mockito = "1"',
      '',
      '[build-dependencies]',
      'cc = "1.0"',
      '',
      "[target.'cfg(windows)'.dev-dependencies]",
      'winapi = "0.3"',
      '',
    ].join('\n');
    const root = tree({ 'Cargo.toml': manifest });
    const r = readCargo(root, ['Cargo.toml']);
    expect(r.deps).toEqual([]);
    expect(r.devSkipped).toBe(3);
    expect(r.notices).toEqual([]);
  });

  it('workspace inheritance, renames and path crates', () => {
    const rootManifest = [
      '[workspace]',
      'members = ["crates/*"]',
      '',
      '[workspace.dependencies]',
      'serde = "1.0"',
      'common = { path = "crates/common" }',
      '',
    ].join('\n');
    const app = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies]',
      'serde.workspace = true',
      'common = { workspace = true }',
      'oai = { package = "async-openai", version = "0.25" }',
      'local = { path = "../local" }',
      '',
    ].join('\n');
    const root = tree({
      'Cargo.toml': rootManifest,
      'crates/app/Cargo.toml': app,
      'crates/common/Cargo.toml': '[package]\nname = "common"\nversion = "0.1.0"\n',
      'Cargo.lock': lock([
        { name: 'app', version: '0.1.0' },
        { name: 'async-openai', version: '0.25.0', source: CRATES },
        { name: 'common', version: '0.1.0' },
        { name: 'serde', version: '1.0.215', source: CRATES },
      ]),
    });
    const r = readCargo(root, ['Cargo.toml', 'crates/app/Cargo.toml', 'crates/common/Cargo.toml']);
    expect(r.deps).toEqual([
      { ecosystem: 'cargo', name: 'serde', version: '1.0.215', manifest: `crates/app/Cargo.toml:${lineOf(app, 'serde.workspace')}` },
      { ecosystem: 'cargo', name: 'async-openai', version: '0.25.0', manifest: `crates/app/Cargo.toml:${lineOf(app, 'oai =')}` },
    ]);
    expect(r.devSkipped).toBe(0);
    expect(r.notices).toEqual([]);
  });

  it('a workspace dev dependency is development, and a workspace path dev dependency is not counted', () => {
    const rootManifest = ['[workspace]', 'members = ["app"]', '', '[workspace.dependencies]', 'mockito = "1"', 'testkit = { path = "testkit" }', ''].join('\n');
    const app = ['[package]', 'name = "app"', 'version = "0.1.0"', '', '[dev-dependencies]', 'mockito = { workspace = true }', 'testkit.workspace = true', ''].join('\n');
    const root = tree({ 'Cargo.toml': rootManifest, 'app/Cargo.toml': app });
    const r = readCargo(root, ['Cargo.toml', 'app/Cargo.toml']);
    expect(r.deps).toEqual([]);
    expect(r.devSkipped).toBe(1);
  });

  it('two locked versions take the caret-compatible one', () => {
    const lockText = lock([
      { name: 'rand', version: '0.7.3', source: CRATES },
      { name: 'rand', version: '0.8.5', source: CRATES },
    ]);
    const caret = ['[package]', 'name = "app"', 'version = "0.1.0"', '', '[dependencies]', 'rand = "0.8"', ''].join('\n');
    const r1 = readCargo(tree({ 'Cargo.toml': caret, 'Cargo.lock': lockText }), ['Cargo.toml']);
    expect(r1.deps).toEqual([{ ecosystem: 'cargo', name: 'rand', version: '0.8.5', manifest: 'Cargo.toml:6' }]);
    expect(r1.notices).toEqual([]);

    const range = ['[package]', 'name = "app"', 'version = "0.1.0"', '', '[dependencies]', 'rand = ">=0.7"', ''].join('\n');
    const r2 = readCargo(tree({ 'Cargo.toml': range, 'Cargo.lock': lockText }), ['Cargo.toml']);
    expect(r2.deps).toEqual([{ ecosystem: 'cargo', name: 'rand', manifest: 'Cargo.toml:6' }]);
    expect(r2.notices).toEqual([UNRESOLVED(1)]);
  });

  it('applies the caret, tilde and exact forms to several locked versions', () => {
    const lockText = lock([
      { name: 'a', version: '0.0.3', source: CRATES },
      { name: 'a', version: '0.0.4', source: CRATES },
      { name: 'b', version: '1.2.0', source: CRATES },
      { name: 'b', version: '1.3.1', source: CRATES },
      { name: 'b', version: '2.0.0', source: CRATES },
      { name: 'c', version: '1.2.3', source: CRATES },
      { name: 'c', version: '1.2.9', source: CRATES },
      { name: 'd', version: '3.1.0', source: CRATES },
      { name: 'd', version: '3.4.0', source: CRATES },
      { name: 'e', version: '1.0.0', source: CRATES },
      { name: 'e', version: '2.0.0', source: CRATES },
    ]);
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies]',
      'a = "0.0.3"',
      'b = "^1.2"',
      'c = "~1.2.3"',
      'd = { version = "=3.1.0" }',
      'e = "*"',
      '',
    ].join('\n');
    const r = readCargo(tree({ 'Cargo.toml': manifest, 'Cargo.lock': lockText }), ['Cargo.toml']);
    expect(r.deps.map((d) => [d.name, d.version])).toEqual([
      ['a', '0.0.3'],
      ['b', '1.3.1'],
      ['c', '1.2.9'],
      ['d', '3.1.0'],
      ['e', undefined],
    ]);
    expect(r.notices).toEqual([UNRESOLVED(1)]);
  });

  it('one row per crate and version: a target repeat is folded, a second version under a rename is kept', () => {
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies]',
      'rand = "0.8"',
      'rand07 = { package = "rand", version = "0.7" }',
      '',
      "[target.'cfg(unix)'.dependencies]",
      'rand = { version = "0.8", features = ["small_rng"] }',
      '',
    ].join('\n');
    const lockText = lock([
      { name: 'rand', version: '0.7.3', source: CRATES },
      { name: 'rand', version: '0.8.5', source: CRATES },
    ]);
    const r = readCargo(tree({ 'Cargo.toml': manifest, 'Cargo.lock': lockText }), ['Cargo.toml']);
    expect(r.deps).toEqual([
      { ecosystem: 'cargo', name: 'rand', version: '0.8.5', manifest: 'Cargo.toml:6' },
      { ecosystem: 'cargo', name: 'rand', version: '0.7.3', manifest: 'Cargo.toml:7' },
    ]);
  });

  it('a git dependency takes the git lock entry', () => {
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies]',
      'openai = { git = "https://github.com/example/openai-rs", branch = "main" }',
      '',
    ].join('\n');
    const root = tree({
      'Cargo.toml': manifest,
      'Cargo.lock': lock([
        { name: 'openai', version: '1.0.0', source: CRATES },
        { name: 'openai', version: '1.1.0-alpha.2', source: 'git+https://github.com/example/openai-rs?branch=main#0123456789abcdef' },
      ]),
    });
    const r = readCargo(root, ['Cargo.toml']);
    expect(r.deps).toEqual([{ ecosystem: 'cargo', name: 'openai', version: '1.1.0-alpha.2', manifest: 'Cargo.toml:6' }]);
    expect(r.notices).toEqual([]);
  });

  it('no lock means no version, one notice', () => {
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies]',
      'serde = "1"',
      'tokio = { version = "1", features = ["full"] }',
      '',
      '[dependencies.reqwest]',
      'version = "0.12"',
      '',
    ].join('\n');
    const r = readCargo(tree({ 'Cargo.toml': manifest }), ['Cargo.toml']);
    expect(r.deps).toEqual([
      { ecosystem: 'cargo', name: 'serde', manifest: 'Cargo.toml:6' },
      { ecosystem: 'cargo', name: 'tokio', manifest: 'Cargo.toml:7' },
      { ecosystem: 'cargo', name: 'reqwest', manifest: 'Cargo.toml:9' },
    ]);
    expect(r.notices).toEqual(['3 Cargo dependencies have no resolved version (no Cargo.lock, or a requirement lexcode could not match to one locked version); recorded without a version']);
  });

  it('takes the lock from the nearest ancestor directory', () => {
    const app = ['[package]', 'name = "app"', 'version = "0.1.0"', '', '[dependencies]', 'serde = "1"', ''].join('\n');
    const root = tree({
      'crates/app/Cargo.toml': app,
      'Cargo.lock': lock([{ name: 'serde', version: '1.0.215', source: CRATES }]),
    });
    const r = readCargo(root, ['crates/app/Cargo.toml']);
    expect(r.deps).toEqual([{ ecosystem: 'cargo', name: 'serde', version: '1.0.215', manifest: 'crates/app/Cargo.toml:6' }]);
  });

  it('ignores [patch] and [replace], and a quoted key is read', () => {
    const manifest = [
      '[package]',
      'name = "app"',
      'version = "0.1.0"',
      '',
      '[dependencies]',
      '"serde_json" = "1"',
      '',
      '[patch.crates-io]',
      'serde = { git = "https://github.com/serde-rs/serde" }',
      '',
      '[replace]',
      '"foo:0.1.0" = { git = "https://github.com/example/foo" }',
      '',
    ].join('\n');
    const r = readCargo(tree({ 'Cargo.toml': manifest, 'Cargo.lock': lock([{ name: 'serde_json', version: '1.0.133', source: CRATES }]) }), ['Cargo.toml']);
    expect(r.deps).toEqual([{ ecosystem: 'cargo', name: 'serde_json', version: '1.0.133', manifest: 'Cargo.toml:6' }]);
    expect(r.devSkipped).toBe(0);
  });

  it('a manifest that does not parse is a notice, not a throw', () => {
    const root = tree({ 'Cargo.toml': '[package\nname = "app"\n' });
    let r: ReturnType<typeof readCargo> | undefined;
    expect(() => {
      r = readCargo(root, ['Cargo.toml']);
    }).not.toThrow();
    expect(r?.deps).toEqual([]);
    expect(r?.notices).toHaveLength(1);
    expect(r?.notices[0]).toMatch(/^Cargo\.toml: did not parse \(invalid TOML( at [^)]*)?\); skipped$/);
  });

  it('a lock that does not parse is a notice, not a throw', () => {
    const manifest = ['[package]', 'name = "app"', 'version = "0.1.0"', '', '[dependencies]', 'serde = "1"', ''].join('\n');
    const root = tree({ 'Cargo.toml': manifest, 'Cargo.lock': '[[package]\nname = "serde"\n' });
    let r: ReturnType<typeof readCargo> | undefined;
    expect(() => {
      r = readCargo(root, ['Cargo.toml']);
    }).not.toThrow();
    expect(r?.deps).toEqual([{ ecosystem: 'cargo', name: 'serde', manifest: 'Cargo.toml:6' }]);
    expect(r?.notices[0]).toMatch(/^Cargo\.lock: did not parse \(invalid TOML( at [^)]*)?\); versions from it are unavailable$/);
    expect(r?.notices.slice(1)).toEqual([UNRESOLVED(1)]);
  });
});
